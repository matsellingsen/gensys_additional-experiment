import os
import re
import requests

# ==============================
# Special tokens
# ==============================
PAD = 0
BOS = 1
EOS = 2

SPECIAL_TOKENS = {
    "<PAD>": PAD,
    "<BOS>": BOS,
    "<EOS>": EOS,
}

# ==============================
# Download utilities
# ==============================
def download_scan_simple_split(base_dir="data"):
    base_url = "https://raw.githubusercontent.com/brendenlake/SCAN/master/simple_split"
    output_dir = os.path.join(base_dir, "simple_split")
    os.makedirs(output_dir, exist_ok=True)

    for fname in ["tasks_train_simple.txt", "tasks_test_simple.txt"]:
        path = os.path.join(output_dir, fname)
        if not os.path.exists(path):
            url = f"{base_url}/{fname}"
            r = requests.get(url)
            r.raise_for_status()
            with open(path, "wb") as f:
                f.write(r.content)

    return output_dir


# ==============================
# Parsing utilities
# ==============================
def load_scan_split(path):
    inputs, outputs = [], []
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            inp = re.findall(r"IN: (.*) OUT:", line)[0]
            out = line.split("OUT: ")[1]
            inputs.append(inp.split())
            outputs.append(out.split())
    return inputs, outputs


# ==============================
# Vocabulary utilities
# ==============================
def build_vocab(seqs):
    vocab = dict(SPECIAL_TOKENS)
    idx = max(vocab.values()) + 1
    for seq in seqs:
        for tok in seq:
            if tok not in vocab:
                vocab[tok] = idx
                idx += 1
    return vocab