import torch
from data_utils.scan_helpers import PAD


def collate_scan_batch(batch):
    """
    Collate function for SCAN batches.

    Each batch item is a tuple:
        (
            source_sequence        : LongTensor [src_len],
            target_input_sequence  : LongTensor [tgt_len + 1],
            target_output_sequence : LongTensor [tgt_len + 1],
        )

    Returns:
        source_batch        : LongTensor [batch_size, max_src_len]
        target_input_batch  : LongTensor [batch_size, max_tgt_len]
        target_output_batch : LongTensor [batch_size, max_tgt_len]
    """
    src_seqs, tgt_in_seqs, tgt_out_seqs = zip(*batch)

    batch_size = len(batch)
    max_src_len = max(seq.size(0) for seq in src_seqs)
    max_tgt_len = max(seq.size(0) for seq in tgt_in_seqs)

    src_batch = torch.full(
        (batch_size, max_src_len),
        PAD,
        dtype=torch.long,
    )
    tgt_in_batch = torch.full(
        (batch_size, max_tgt_len),
        PAD,
        dtype=torch.long,
    )
    tgt_out_batch = torch.full(
        (batch_size, max_tgt_len),
        PAD,
        dtype=torch.long,
    )

    for i in range(batch_size):
        src_len = src_seqs[i].size(0)
        tgt_len = tgt_in_seqs[i].size(0)

        src_batch[i, :src_len] = src_seqs[i]
        tgt_in_batch[i, :tgt_len] = tgt_in_seqs[i]
        tgt_out_batch[i, :tgt_len] = tgt_out_seqs[i]

    return src_batch, tgt_in_batch, tgt_out_batch