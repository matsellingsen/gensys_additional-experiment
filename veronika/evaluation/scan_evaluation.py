import torch
from data_utils.scan_helpers import PAD, BOS, EOS


# --------------------------------------------------
# Greedy decoding (with optional oracle)
# --------------------------------------------------
@torch.no_grad()
def greedy_decode(
    model,
    src,
    device,
    use_oracle=False,
    target_output_lengths=None,
    max_len=40,
):
    """
    Greedy decoding for SCAN.
    If use_oracle=True, prevents early EOS and forces EOS at target length.
    """
    model.eval()
    src = src.to(device)

    B = src.size(0)
    decoded = torch.full(
        (B, 1),
        BOS,
        dtype=torch.long,
        device=device,
    )

    finished = torch.zeros(B, dtype=torch.bool, device=device)

    for step in range(max_len):
        logits = model(src, decoded)
        next_tokens = logits[:, -1].argmax(dim=-1, keepdim=True)

        if use_oracle:
            assert target_output_lengths is not None
            for i in range(B):
                tgt_len = int(target_output_lengths[i])

                # too early → forbid EOS
                if step + 1 < tgt_len and next_tokens[i].item() == EOS:
                    logits_i = logits[i, -1]
                    logits_i[EOS] = float("-inf")
                    next_tokens[i] = logits_i.argmax()

                # at or after target length → force EOS
                if step + 1 >= tgt_len:
                    next_tokens[i] = EOS

        finished |= (next_tokens.squeeze(1) == EOS)
        next_tokens[finished] = EOS

        decoded = torch.cat([decoded, next_tokens], dim=1)

        if finished.all():
            break

    return decoded


# --------------------------------------------------
# Sequence-level accuracy
# --------------------------------------------------
def sequence_accuracy(preds, targets):
    """
    Exact-match sequence accuracy.
    """
    correct = 0
    total = targets.size(0)

    preds = preds.cpu()
    targets = targets.cpu()

    for p, t in zip(preds, targets):
        p = p.tolist()
        t = t.tolist()

        # remove BOS
        if len(p) > 0 and p[0] == BOS:
            p = p[1:]

        # cut at EOS
        if EOS in p:
            p = p[: p.index(EOS) + 1]
        if EOS in t:
            t = t[: t.index(EOS) + 1]

        if p == t:
            correct += 1

    return correct / total if total > 0 else 0.0


@torch.no_grad()
def evaluate_sequence_accuracy(
    model,
    dataloader,
    device,
    use_oracle=False,
):
    """
    Sequence-level accuracy.
    If use_oracle=True, uses oracle target lengths.
    """
    model.eval()
    total_correct = 0
    total_samples = 0

    for src, _, tgt_out in dataloader:
        src = src.to(device)
        tgt_out = tgt_out.to(device)

        if use_oracle:
            target_lengths = (tgt_out != PAD).sum(dim=1)
        else:
            target_lengths = None

        preds = greedy_decode(
            model,
            src,
            device,
            use_oracle=use_oracle,
            target_output_lengths=target_lengths,
        )

        batch_acc = sequence_accuracy(preds, tgt_out)
        total_correct += batch_acc * src.size(0)
        total_samples += src.size(0)

    return total_correct / total_samples if total_samples > 0 else 0.0


# --------------------------------------------------
# Token-level accuracy (teacher forcing)
# --------------------------------------------------
@torch.no_grad()
def evaluate_token_level(
    model,
    dataloader,
    criterion,
    device,
):
    """
    Token-level accuracy (ignoring PAD).
    """
    model.eval()
    total_correct = 0
    total_tokens = 0
    total_loss = 0.0

    for src, tgt_in, tgt_out in dataloader:
        src = src.to(device)
        tgt_in = tgt_in.to(device)
        tgt_out = tgt_out.to(device)

        logits = model(src, tgt_in)

        loss = criterion(
            logits.view(-1, logits.size(-1)),
            tgt_out.view(-1),
        )
        total_loss += loss.item()

        preds = logits.argmax(dim=-1)
        mask = tgt_out != PAD

        total_correct += ((preds == tgt_out) & mask).sum().item()
        total_tokens += mask.sum().item()

    token_acc = total_correct / total_tokens if total_tokens > 0 else 0.0
    avg_loss = total_loss / len(dataloader)

    return avg_loss, token_acc


# --------------------------------------------------
# Ordered token accuracy (jump curve)
# --------------------------------------------------
@torch.no_grad()
def evaluate_ordered_token_accuracy(
    model,
    dataloader,
    device,
):
    """
    Ordered token accuracy (used for jump curve).
    """
    model.eval()
    total_correct = 0
    total_tokens = 0

    for src, _, tgt_out in dataloader:
        src = src.to(device)
        tgt_out = tgt_out.to(device)

        preds = greedy_decode(
            model,
            src,
            device,
            use_oracle=False,
        )
        preds = preds[:, 1:]  # drop BOS

        for p, t in zip(preds, tgt_out):
            for pi, ti in zip(p.tolist(), t.tolist()):
                if ti == PAD:
                    break
                if pi == ti:
                    total_correct += 1
                total_tokens += 1

    return total_correct / total_tokens if total_tokens > 0 else 0.0